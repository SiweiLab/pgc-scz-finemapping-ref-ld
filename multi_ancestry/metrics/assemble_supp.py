#!/usr/bin/env python3
"""Supplementary figures, numbered: copy each source figure (and its caption) to figures/v2/supp/SuppFig<N><panel>.png.

The ORDER LIVES HERE, in MANIFEST, and nowhere else. Source files keep the names their scripts write, so re-running a
plotting script never needs to know the numbering; re-run this afterwards. To renumber, reorder MANIFEST and re-run:
the old numbered copies are removed first. It also writes supp/INDEX.md (number -> source -> script) for the
Methods and Supplementary text.
"""
import glob
import os
import shutil

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "figures", "v2")
OUT = os.path.join(SRC, "supp")

# (number, panel, source png, title, script that makes it). panel "" = a single-panel figure.
MANIFEST = [   # numbered by first citation in the text (renumbered 2026-10-14)
    (1, "", "supp_fig1_design_domains.png", "Data and variants analyzed",
     "the hand-drawn flowchart (supp fig1A.png) + plot_variant_domains.py --v2 --arms-only; compose_supp1.py"),
    (2, "", "supp_fig4_pr_variants.png", "Precision-recall under alternative scoring and variant sets (a-c)",
     "plot_sensfdr_curve.py --pr [--all-variants] on both trees, then compose_supp4.py"),
    (3, "", "supp_fig5_Lsweep.png", "Precision-recall across the number of modelled causal effects",
     "plot_Lsweep_curve.py --pr [--all-variants] --suffix=-noambig, then compose_supp5.py"),
    (4, "", "supp_fig2_recovery_strata.png", "Top-variant recovery across locus sets and credible-set purity conventions",
     "plot_supp_fig2_recovery.py"),
    (5, "", "supp_published_benchmark.png", "Changing one variable at a time: published in-sample analyses as the benchmark",
     "plot_supp_published_benchmark.py"),
    (6, "", "supp_published_vs_ref.png", "Published in-sample merged-LD fine-mapping against the benchmark",
     "plot_supp_published_vs_ref.py"),
    (7, "", "supp_resolution_pip05.png", "Fine-mapping resolution against the benchmark",
     "plot_supp_resolution.py"),
    (8, "", "supp_fig8_kriging_pr.png", "Consistency of association statistics with reference LD at the Fig. 2b locus, "
     "and fine-mapping concordance without high-s loci",
     "plot_supp_kriging.py (B57 kriging tables) + plot_sensfdr_curve.py --pr --s-flag 0.01 (B70 susieR s); compose_supp8.py"),
    (9, "", "supp_susiex_eur_panel.png", "SuSiEx with UK Biobank versus All of Us European LD",
     "plot_supp_susiex_eur_panel.py (numbers: supp_susiex_eur_panel.py)"),
    (10, "", "eur_panels_b53.png", "European-only fine-mapping under three European reference panels",
     "plot_eur_panels_b53.py"),
    (11, "", "supp_eur_only.png", "Merged LD versus European-only fine-mapping",
     "plot_supp_eur_only.py"),
]


def main():
    os.makedirs(OUT, exist_ok=True)
    for f in glob.glob(os.path.join(OUT, "SuppFig*")):
        os.remove(f)
    lines = ["# Supplementary figures (generated by metrics/assemble_supp.py -- edit MANIFEST there, not this file)", "",
             "| # | Title | File | Source | Made by |", "|---|---|---|---|---|"]
    for num, panel, src, title, how in MANIFEST:
        tag = f"SuppFig{num}{panel}"
        if src is None or not os.path.exists(os.path.join(SRC, src)):
            lines.append(f"| {num}{panel} | {title} | **missing** | {src or '-'} | {how} |")
            print(f"  {tag}: MISSING ({src})")
            continue
        shutil.copy2(os.path.join(SRC, src), os.path.join(OUT, f"{tag}.png"))
        cap = os.path.join(SRC, src.rsplit(".", 1)[0] + "_caption.txt")
        if os.path.exists(cap):
            shutil.copy2(cap, os.path.join(OUT, f"{tag}_caption.txt"))
        lines.append(f"| {num}{panel} | {title} | `supp/{tag}.png` | `{src}` | {how} |")
        print(f"  {tag} <- {src}")
    open(os.path.join(OUT, "INDEX.md"), "w").write("\n".join(lines) + "\n")
    print(f"[done] {OUT}/INDEX.md")


if __name__ == "__main__":
    main()
